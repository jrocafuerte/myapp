export type MessageCode = keyof typeof DEFAULT_MESSAGES;
export type MessageParams = Record<string, string | number>;

export const isMessageCode = (x: string): x is MessageCode => Object.prototype.hasOwnProperty.call(DEFAULT_MESSAGES, x);

/** Variables que usa una plantilla: "Saldo insuficiente en {alias}." → ["alias"]. */
export const placeholders = (template: string) => [...template.matchAll(/\{(\w+)\}/g)].map((m) => m[1]);

/** Completa una plantilla. Una variable sin valor se deja tal cual, para que el error sea visible. */
export const formatMessage = (template: string, params: MessageParams = {}) =>
  template.replace(/\{(\w+)\}/g, (all, k: string) => (k in params ? String(params[k]) : all));
